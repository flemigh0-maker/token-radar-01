// Token Radar's model, radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks launch candidates: protocols that record no token and are not a wrapped,
// staked or bridged product of a token that already trades, and not an exchange. The watchlist
// is the floor (every one of its 40 slugs is ranked); the early radar adds every other
// candidate the snapshot holds, below the floor and above it. Live-token protocols are kept
// apart and shown with the market's own values, never mixed into the ranking.
//
// Implied value is calibrated on the snapshot's own live market, not on a hardcoded multiple:
//
//   category_multiple = median(mcap_usd / tvl_usd) over live-token protocols in the same
//                       category, when at least 3 of them report both figures; else the
//                       global median over all live-token protocols. Clamped to [0.05, 1.5].
//   growth_mult       = 1 + clamp(change_7d, -60, 120) / 100 * 0.5
//   maturity_mult     = 0.6 + min(age_days, 1095) / 1095 * 0.4   (age unknown: 365 days)
//   chain_mult        = 1 + 0.015 * min(chains - 1, 10)
//   implied           = max(1, round(tvl_usd * category_multiple * growth_mult
//                                      * maturity_mult * chain_mult))
//
// No protocol name is ever special-cased: the same function scores every row, and the
// dashboard shows the calibration table it was scored with.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
